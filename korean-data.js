    'ㅍ': [[[22, 22], [78, 22]], [[38, 22], [38, 78]], [[62, 22], [62, 78]], [[22, 78], [78, 78]]],
    'ㅎ': [[[50, 12], [50, 28]], [[25, 38], [75, 38]], circ(50, 63, 17, 32)],
    'ㅏ': [[[42, 15], [42, 85]], [[42, 50], [68, 50]]],
    'ㅑ': [[[42, 15], [42, 85]], [[42, 38], [66, 38]], [[42, 62], [66, 62]]],
    'ㅓ': [[[58, 15], [58, 85]], [[32, 50], [58, 50]]],
    'ㅕ': [[[58, 15], [58, 85]], [[34, 38], [58, 38]], [[34, 62], [58, 62]]],
    'ㅗ': [[[50, 22], [50, 52]], [[20, 52], [80, 52]]],
    'ㅛ': [[[38, 22], [38, 52]], [[62, 22], [62, 52]], [[20, 52], [80, 52]]],
